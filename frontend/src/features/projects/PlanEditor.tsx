import { AlertTriangle, CheckCircle2, CircleX, Plus, Trash2 } from "lucide-react";
import { useMemo, useState } from "react";
import { toast } from "sonner";

import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { NativeSelect } from "@/components/ui/native-select";
import { ApiError } from "@/lib/api-client";
import { cn } from "@/lib/utils";
import type { PlanIssue, PlanRecord, PlanStep, TestDataRef, TestPlan } from "@/types/api";

import { useApprovePlan, useSavePlan } from "./api";
import { blankStep } from "./plan-actions";
import { StepEditor, type StepMessage } from "./StepEditor";

const textareaClass =
  "w-full rounded-control border border-border-strong bg-sunken px-3 py-2 text-sm placeholder:text-faint " +
  "focus-visible:border-beacon focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-beacon-soft";

interface ServerError {
  message: string;
  byStep: Map<number, string[]>;
}

/** Map a 422 validation envelope to per-step messages (loc: body.plan.steps.<i>...). */
function serverError(error: unknown): ServerError | null {
  if (!(error instanceof ApiError)) return error ? { message: "Could not save the plan.", byStep: new Map() } : null;
  const byStep = new Map<number, string[]>();
  if (Array.isArray(error.details)) {
    for (const item of error.details as { loc?: unknown[]; msg?: string; step?: number; message?: string }[]) {
      const stepIndex = item.loc?.[2] === "steps" && typeof item.loc[3] === "number" ? item.loc[3] : item.step;
      const text = (item.msg ?? item.message ?? "").replace(/^Value error, /, "");
      if (typeof stepIndex === "number" && text) byStep.set(stepIndex, [...(byStep.get(stepIndex) ?? []), text]);
    }
  }
  const message =
    error.code === "request.validation_failed" ? "Some steps are incomplete. Fix the highlighted fields." : error.message;
  return { message, byStep };
}

function lines(value: string): string[] {
  return value
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
}

export function PlanEditor({
  projectId,
  caseId,
  record,
  initial,
}: {
  projectId: string;
  caseId: string;
  record: PlanRecord | null;
  initial: TestPlan;
}) {
  const [plan, setPlan] = useState<TestPlan>(initial);
  const [preconditions, setPreconditions] = useState((initial.preconditions ?? []).join("\n"));
  const [expected, setExpected] = useState((initial.expected_results ?? []).join("\n"));
  const save = useSavePlan(projectId, caseId);
  const approve = useApprovePlan(projectId, caseId);

  const current: TestPlan = useMemo(
    () => ({ ...plan, preconditions: lines(preconditions), expected_results: lines(expected) }),
    [plan, preconditions, expected],
  );
  const dirty = record === null || JSON.stringify(current) !== JSON.stringify(normalizeForCompare(initial));
  const issues: PlanIssue[] = dirty ? [] : (record?.issues ?? []);
  const errors = issues.filter((i) => i.severity === "error");
  const failure = serverError(save.error) ?? serverError(approve.error);

  const stepMessages = (index: number): StepMessage[] => [
    ...(failure?.byStep.get(index) ?? []).map((message) => ({ severity: "error" as const, message })),
    ...issues.filter((i) => i.step === index).map((i) => ({ severity: i.severity, message: i.message })),
  ];

  const setSteps = (steps: PlanStep[]) => setPlan((p) => ({ ...p, steps }));
  const setTestData = (test_data: TestDataRef[]) => setPlan((p) => ({ ...p, test_data }));
  const editable = record?.status !== "approved";

  const onSave = () =>
    save.mutate(
      { planId: record && record.status === "draft" ? record.id : null, plan: current },
      { onSuccess: () => toast.success(record?.status === "approved" ? "Saved as a new draft" : "Draft saved") },
    );

  const onApprove = () =>
    record &&
    approve.mutate(record.id, {
      onSuccess: (version) => toast.success(`Approved as version ${version.version}`),
    });

  return (
    <section aria-labelledby="plan-heading" className="space-y-5">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <h2 id="plan-heading" className="text-lg font-semibold">
            Test plan
          </h2>
          <p className="text-[13px] text-muted">
            {record === null
              ? "New plan, not saved yet."
              : `Revision ${record.revision}, ${record.status === "approved" ? "approved" : "draft"}${
                  record.source === "ai" ? ", generated by AI" : record.source === "edited" ? ", edited by you" : ", written by you"
                }.`}
            {!editable ? " Approved plans are immutable: your changes will be saved as a new draft." : ""}
          </p>
        </div>
        <div className="flex items-center gap-2">
          {dirty && record !== null ? <span className="text-[13px] text-warning">Unsaved changes</span> : null}
          <Button variant="secondary" onClick={onSave} disabled={!dirty || save.isPending}>
            {save.isPending ? "Saving…" : editable ? "Save draft" : "Save as new draft"}
          </Button>
          {record?.status === "draft" ? (
            <Button
              onClick={onApprove}
              disabled={dirty || errors.length > 0 || approve.isPending}
              title={dirty ? "Save the draft first" : errors.length ? "Fix the errors first" : undefined}
            >
              <CheckCircle2 /> {approve.isPending ? "Approving…" : "Approve plan"}
            </Button>
          ) : null}
        </div>
      </div>

      {failure ? (
        <p role="alert" className="flex items-start gap-2 rounded-control border border-failed/40 bg-failed/10 px-3 py-2 text-sm">
          <CircleX className="mt-0.5 size-4 shrink-0 text-failed" aria-hidden /> {failure.message}
        </p>
      ) : null}
      {issues.filter((i) => i.step === null).map((issue) => (
        <p
          key={issue.code}
          className={cn("flex items-start gap-2 text-[13px]", issue.severity === "error" ? "text-failed" : "text-warning")}
        >
          {issue.severity === "error" ? <CircleX className="mt-0.5 size-4 shrink-0" aria-hidden /> : <AlertTriangle className="mt-0.5 size-4 shrink-0" aria-hidden />}
          {issue.message}
        </p>
      ))}

      <div className="grid gap-4 md:grid-cols-2">
        <div className="space-y-1.5 md:col-span-2">
          <Label htmlFor="plan-name">Plan name</Label>
          <Input id="plan-name" value={plan.name} maxLength={200} onChange={(e) => setPlan({ ...plan, name: e.target.value })} />
        </div>
        <div className="space-y-1.5">
          <Label htmlFor="plan-preconditions">Preconditions, one per line</Label>
          <textarea id="plan-preconditions" rows={3} className={textareaClass} value={preconditions} onChange={(e) => setPreconditions(e.target.value)} />
        </div>
        <div className="space-y-1.5">
          <Label htmlFor="plan-expected">Expected results, one per line</Label>
          <textarea id="plan-expected" rows={3} className={textareaClass} value={expected} onChange={(e) => setExpected(e.target.value)} />
        </div>
      </div>

      <fieldset className="space-y-2">
        <legend className="text-[13px] font-medium text-muted">Test data</legend>
        <p className="text-xs text-faint">
          Steps reference these as {"{{env.NAME}}"} or {"{{secret.NAME}}"}. Values live in the environment, never in the plan
          or the code, and secret values are never sent to AI providers.
        </p>
        {(plan.test_data ?? []).map((ref, index) => (
          <div key={index} className="flex flex-wrap items-center gap-2">
            <Input
              aria-label={`Test data ${index + 1} name`}
              value={ref.name}
              onChange={(e) => {
                const next = [...(plan.test_data ?? [])];
                next[index] = { ...ref, name: e.target.value.toUpperCase().replace(/[^A-Z0-9_]/g, "_") };
                setTestData(next);
              }}
              className="h-9 w-48 font-mono text-[13px]"
            />
            <NativeSelect
              aria-label={`Test data ${index + 1} kind`}
              value={ref.kind}
              onChange={(e) => {
                const next = [...(plan.test_data ?? [])];
                next[index] = { ...ref, kind: e.target.value as TestDataRef["kind"] };
                setTestData(next);
              }}
              className="w-32"
            >
              <option value="env">Plain</option>
              <option value="secret">Secret</option>
            </NativeSelect>
            <Input
              aria-label={`Test data ${index + 1} description`}
              placeholder="Description"
              value={ref.description ?? ""}
              onChange={(e) => {
                const next = [...(plan.test_data ?? [])];
                next[index] = { ...ref, description: e.target.value };
                setTestData(next);
              }}
              className="h-9 min-w-40 flex-1 text-[13px]"
            />
            <Button
              variant="ghost"
              size="icon"
              className="size-8"
              aria-label={`Remove test data ${ref.name || index + 1}`}
              onClick={() => setTestData((plan.test_data ?? []).filter((_, i) => i !== index))}
            >
              <Trash2 />
            </Button>
          </div>
        ))}
        <Button
          variant="ghost"
          size="sm"
          onClick={() => setTestData([...(plan.test_data ?? []), { name: "NEW_VARIABLE", kind: "env", description: "" }])}
        >
          <Plus /> Add test data
        </Button>
      </fieldset>

      <div className="space-y-2">
        <p className="text-[13px] font-medium text-muted">Steps</p>
        <ol className="space-y-2">
          {plan.steps.map((step, index) => (
            <StepEditor
              key={index}
              step={step}
              index={index}
              messages={stepMessages(index)}
              isFirst={index === 0}
              isLast={index === plan.steps.length - 1}
              onChange={(next) => setSteps(plan.steps.map((s, i) => (i === index ? next : s)))}
              onRemove={() => setSteps(plan.steps.filter((_, i) => i !== index))}
              onMove={(delta) => {
                const next = [...plan.steps];
                const [moved] = next.splice(index, 1);
                if (moved) next.splice(index + delta, 0, moved);
                setSteps(next);
              }}
            />
          ))}
        </ol>
        <Button variant="secondary" size="sm" onClick={() => setSteps([...plan.steps, blankStep("click")])} disabled={plan.steps.length >= 100}>
          <Plus /> Add step
        </Button>
      </div>
    </section>
  );
}

/** The server returns optional fields filled with defaults; compare like with like. */
function normalizeForCompare(plan: TestPlan): TestPlan {
  return {
    ...plan,
    preconditions: plan.preconditions ?? [],
    expected_results: plan.expected_results ?? [],
  };
}
